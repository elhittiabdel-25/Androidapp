"""Write the card film test's data: for each card to record, its voice clips (the card's face) on a timeline.

    python3 tools/previews/gen_film_data.py <cards.json> <assets dir> <out FilmData.kt> <out plan.json> [ids]

The timeline starts with a short lead-in, plays the clips back to back as the app does, and holds at the end.
plan.json gives film_assemble.py the same timeline for the sound.
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LEAD, GAP, TAIL = 1.2, 0.12, 2.5


def duration(path):
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path],
                       capture_output=True, text=True, check=True)
    return float(r.stdout.strip())


def main(src, assets, out_kt, out_plan, ids_arg=""):
    pack = json.load(open(src, encoding="utf-8"))
    cards = {c["id"]: c for c in pack["cards"]}
    ids = [i.strip() for i in ids_arg.split(",") if i.strip()] or \
        [l.strip() for l in open(os.path.join(HERE, "film.txt"), encoding="utf-8") if l.strip() and not l.startswith("#")]
    films, plan = [], {}
    for cid in ids:
        c = cards[cid]
        t = LEAD
        clips = []
        for a in c["audio"]:
            if a.get("layer") != "face":
                continue
            path = os.path.join(assets, a["file"])
            d = duration(path)
            clips.append((a["key"], t, d, path))
            t += d + GAP
        total = t - GAP + TAIL
        films.append((cid, clips, total))
        plan[cid] = {"total": total, "clips": [{"file": p, "start": s} for _, s, _, p in clips]}
    lines = [
        "package app.usulcards",
        "",
        "// Generated by tools/previews/gen_film_data.py: do not edit.",
        "class FilmClip(val key: String, val start: Float, val dur: Float)",
        "class Film(val id: String, val clips: List<FilmClip>, val total: Float)",
        "",
        "object FilmData {",
        "    val films: List<Film> = listOf(",
    ]
    for cid, clips, total in films:
        cl = ", ".join(f'FilmClip("{k}", {s:.3f}f, {d:.3f}f)' for k, s, d, _ in clips)
        lines.append(f'        Film("{cid}", listOf({cl}), {total:.3f}f),')
    lines += ["    )", "}", ""]
    open(out_kt, "w", encoding="utf-8").write("\n".join(lines))
    json.dump(plan, open(out_plan, "w"), indent=1)
    print(f"{len(films)} film(s): " + ", ".join(f"{c} {t:.1f}s" for c, _, t in films))


if __name__ == "__main__":
    main(*sys.argv[1:6])
