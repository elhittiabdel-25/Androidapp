"""Write the preview test's data: every illustrated scene of the content pack, as Kotlin source.

    python3 tools/previews/gen_preview_data.py <cards.json> <out PreviewData.kt> [motion ids, comma-separated]

Motion ids (default: tools/previews/motion.txt) are rendered frame by frame for an animation; every scene
also gets one still per beat. Kotlin source instead of JSON: the JVM test then needs no JSON parser.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def kstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n") + '"'


def main(src, out, motion_arg):
    pack = json.load(open(src, encoding="utf-8"))
    if motion_arg.strip():
        motion = [m.strip() for m in motion_arg.split(",") if m.strip()]
    else:
        motion = [l.strip() for l in open(os.path.join(HERE, "motion.txt"), encoding="utf-8") if l.strip() and not l.startswith("#")]
    lines = [
        "package app.usulcards",
        "",
        "import app.usulcards.data.Scene",
        "import app.usulcards.data.SceneItem",
        "",
        "// Generated by tools/previews/gen_preview_data.py: do not edit.",
        "object PreviewData {",
        "    val motion: Set<String> = setOf(" + ", ".join(kstr(m) for m in motion) + ")",
        "    val scenes: List<Pair<String, Scene>> = listOf(",
    ]
    n = 0
    for c in pack["cards"]:
        sc = c.get("scene")
        if not sc or sc.get("type") != "art":
            continue
        n += 1
        items = []
        for it in sc["items"]:
            items.append(
                "SceneItem(label = %s, sub = %s, at = %s, frac = %sf, side = %d, value = %sf, kind = %s)" % (
                    kstr(it.get("label", "")), kstr(it.get("sub", "")), kstr(it.get("at", "")),
                    float(it.get("frac", 0.0)), int(it.get("side", -1)), float(it.get("value", 0.0)), kstr(it.get("kind", ""))))
        sides = ", ".join("%s to %s" % (kstr(s.get("title", "")), kstr(s.get("tone", ""))) for s in sc.get("sides", []))
        lines.append("        %s to Scene(" % kstr(c["id"]))
        lines.append("            type = %s, layout = %s, title = %s, tone = %s," % (
            kstr(sc["type"]), kstr(sc.get("layout", "")), kstr(sc.get("title", "")), kstr(sc.get("tone", ""))))
        lines.append("            sides = listOf(%s)," % sides)
        lines.append("            items = listOf(")
        for x in items:
            lines.append("                %s," % x)
        lines.append("            ),")
        lines.append("            note = %s," % kstr(sc.get("note", "")))
        lines.append("        ),")
    lines.append("    )")
    lines.append("}")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"{n} illustrated scenes, motion: {', '.join(motion) or 'none'} -> {out}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else "")
