"""Card animations ("scenes"), one per card. Built into the app by build_scenes.py.

Each item appears when the card's audio reaches clip `at` (title, face-0, deep-1...) and the cue word in it.
`cue=None` means the start of the clip; `at` defaults to the previous item's clip.
A label written WITHOUT harakat is copied, fully vowelled, from the card's own vowelled text (the build fails
if it is not there); a label written WITH harakat is used as written and checked against the card's words.

Scene types: steps (layout list / grid / stairs), sides, chain (tone danger / good), timeline, circles,
meter, transform, moon, stars. Rules: no people or animals, no depiction of Allah, the angels or the Throne.
"""


def I(label, cue=None, at=None, sub="", side=None, value=None, kind=""):
    d = {"label": label, "cue": cue, "sub": sub, "kind": kind}
    if at is not None:
        d["at"] = at
    if side is not None:
        d["side"] = side
    if value is not None:
        d["value"] = value
    return d


def S(type, items, layout="", title="", tone="", sides=(), note=""):
    return {"type": type, "layout": layout, "title": title, "tone": tone,
            "sides": [{"title": t, "tone": k} for t, k in sides], "items": items, "note": note}


